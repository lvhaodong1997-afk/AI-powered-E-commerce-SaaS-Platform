CREATE TABLE IF NOT EXISTS tk_open_youtube_auth_session (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    session_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    client_id VARCHAR(64) NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    end_user_id VARCHAR(128),
    launch_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin,
    verifier_cipher TEXT,
    status VARCHAR(24) NOT NULL,
    connection_id VARCHAR(48),
    fail_code VARCHAR(64),
    expire_time DATETIME NOT NULL,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_yt_session (session_id), UNIQUE KEY uk_yt_state (state_hash), KEY idx_yt_session_expire (expire_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tk_open_youtube_connection (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    connection_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    client_id VARCHAR(64) NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    external_channel_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    channel_title VARCHAR(256) NOT NULL,
    token_cipher TEXT,
    token_expires_at DATETIME,
    status VARCHAR(24) NOT NULL,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_yt_connection (connection_id),
    UNIQUE KEY uk_yt_channel (client_id,workspace_id,external_channel_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tk_open_youtube_media (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    upload_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    media_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin,
    client_id VARCHAR(64) NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    file_name VARCHAR(256) NOT NULL,
    file_size BIGINT NOT NULL,
    content_type VARCHAR(128),
    sha256 CHAR(64),
    upload_mode VARCHAR(16) NOT NULL,
    object_key VARCHAR(512),
    object_etag VARCHAR(256),
    file_url VARCHAR(2048),
    uploaded_size BIGINT NOT NULL DEFAULT 0,
    uploaded_chunks TEXT,
    status VARCHAR(24) NOT NULL,
    fail_reason VARCHAR(512),
    expire_time DATETIME NOT NULL,
    completed_time DATETIME,
    creator VARCHAR(64) DEFAULT '', updater VARCHAR(64) DEFAULT '',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted BIT NOT NULL DEFAULT b'0',
    UNIQUE KEY uk_yt_upload (upload_id), UNIQUE KEY uk_yt_media (media_id), KEY idx_yt_media_expire (expire_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tk_open_youtube_publish_task (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    task_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    client_id VARCHAR(64) NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    connection_id VARCHAR(48) NOT NULL,
    media_id VARCHAR(64) NOT NULL,
    file_size BIGINT NOT NULL,
    idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payload_hash CHAR(64) NOT NULL,
    title VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    privacy_status VARCHAR(12) NOT NULL,
    made_for_kids BOOLEAN NOT NULL,
    contains_synthetic_media BOOLEAN NOT NULL,
    upload_cipher TEXT,
    youtube_video_id VARCHAR(16),
    upload_offset BIGINT NOT NULL DEFAULT 0,
    platform_status VARCHAR(32),
    status VARCHAR(24) NOT NULL,
    fail_code VARCHAR(64),
    retryable BOOLEAN NOT NULL DEFAULT FALSE,
    attempt INT NOT NULL DEFAULT 0,
    transient_errors INT NOT NULL DEFAULT 0,
    poll_count INT NOT NULL DEFAULT 0,
    next_retry_time DATETIME,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_yt_task (task_id), UNIQUE KEY uk_yt_idempotency (client_id,idempotency_key),
    KEY idx_yt_task_due (status,next_retry_time,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
