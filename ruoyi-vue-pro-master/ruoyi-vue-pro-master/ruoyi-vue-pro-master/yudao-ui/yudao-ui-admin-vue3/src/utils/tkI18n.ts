export const isEnglishLocale = () => useLocaleStore().getCurrentLocale.lang === 'en'

export const tkText = (zh: string, en: string) => (isEnglishLocale() ? en : zh)

export const translateTkTitle = (title?: string) => {
  if (!title || !isEnglishLocale()) {
    return title || ''
  }
  return titleMap[title] || title
}

export const translateUiText = (text?: string) => {
  if (!text || !isEnglishLocale()) {
    return text || ''
  }
  const catalogText = translateTkTextByLocale(text, 'en')
  if (catalogText !== text) {
    return catalogText
  }
  return uiTextMap[text] || text
}

export const translateUiTextWithWhitespace = (text?: string) => {
  if (!text) {
    return ''
  }
  const leading = text.match(/^\s*/)?.[0] || ''
  const trailing = text.match(/\s*$/)?.[0] || ''
  const trimmed = text.trim()
  const translated = translateUiText(trimmed)
  return translated === trimmed ? text : `${leading}${translated}${trailing}`
}
