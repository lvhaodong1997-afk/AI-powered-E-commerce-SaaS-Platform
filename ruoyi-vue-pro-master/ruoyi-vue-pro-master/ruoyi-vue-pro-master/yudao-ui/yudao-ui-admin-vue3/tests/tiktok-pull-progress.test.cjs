const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const page = fs.readFileSync(path.join(__dirname, '../src/views/tk/video-publish-center/index.vue'), 'utf8')
const label = page.match(/const tiktokStatusLabel = \(status\?: string\) => \((\{[\s\S]*?\})\)\[status \|\| ''\]/)
assert.ok(label, 'status labels can be inspected')
const labels = new Function(`return (${label[1]})`)()
assert.equal(labels.PROCESSING_DOWNLOAD, 'TikTok拉取中')
assert.equal(labels.PROCESSING_UPLOAD, '上传中')
assert.equal(labels.PROCESSING, '平台处理中')
assert.equal(labels.PUBLISH_COMPLETE, '已发布')
assert.equal(labels.SEND_TO_USER_INBOX, '已提交草稿箱')
assert.notEqual(labels.SEND_TO_USER_INBOX, labels.PUBLISH_COMPLETE)
console.log('TikTok pull progress status labels passed')
